static HAL_StatusTypeDef SSD1306_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};   /* Co=0,D/C#=0 -> 命令 */
    return HAL_I2C_Master_Transmit(s_hi2c, SSD1306_ADDR, buf, 2, 100);
}

HAL_StatusTypeDef SSD1306_Init(I2C_HandleTypeDef *hi2c)
{
    s_hi2c = hi2c;
    HAL_Delay(100);                 /* 上电等待稳定 (VDD/VBAT 时序) */

    const uint8_t init_seq[] = {
        0xAE,       /* 关显示 */
        0xD5, 0x80, /* 时钟分频/振荡频率 */
        0xA8, 0x3F, /* 复用率 1/64 */
        0xD3, 0x00, /* 显示偏移 0 */
        0x40,       /* 起始行 0 */
        0x8D, 0x14, /* 电荷泵使能 */
        0x20, 0x00, /* 水平寻址模式 */
        0xA1,       /* 段重映射: 列127 -> SEG0 */
        0xC8,       /* COM 扫描方向: 逆序 */
        0xDA, 0x12, /* COM 引脚配置 */
        0x81, 0xCF, /* 对比度 207 */
        0xD9, 0xF1, /* 预充电周期 */
        0xDB, 0x40, /* VCOMH 电压 0.77xVcc */
        0xA4,       /* 显示跟随显存 */
        0xA6,       /* 正常显示(非反色) */
        0xAF        /* 开显示 */
    };
    for (uint32_t i = 0; i < sizeof(init_seq); i++)
        if (SSD1306_WriteCmd(init_seq[i]) != HAL_OK)
            return HAL_ERROR;

    SSD1306_Clear();
    SSD1306_Update();
    return HAL_OK;
}

void SSD1306_Clear(void) { memset(s_vram, 0x00, sizeof(s_vram)); }
void SSD1306_Fill(uint8_t pattern) { memset(s_vram, pattern, sizeof(s_vram)); }

void SSD1306_Update(void)
{
    /* 水平寻址模式下一次性写入整帧 */
    uint8_t cmd[] = {0x22, 0x00, 0x07};   /* 页地址 0~7 */
    uint8_t cmd2[] = {0x21, 0x00, 0x7F};  /* 列地址 0~127 */
    HAL_I2C_Master_Transmit(s_hi2c, SSD1306_ADDR, cmd, 3, 100);
    HAL_I2C_Master_Transmit(s_hi2c, SSD1306_ADDR, cmd2, 3, 100);

    uint8_t buf[SSD1306_WIDTH + 1];
    buf[0] = 0x40;                        /* D/C#=1 -> 数据 */
    for (uint8_t page = 0; page < 8; page++) {
        memcpy(&buf[1], &s_vram[page * SSD1306_WIDTH], SSD1306_WIDTH);
        HAL_I2C_Master_Transmit(s_hi2c, SSD1306_ADDR, buf,
                                SSD1306_WIDTH + 1, 100);
    }
}

void SSD1306_DrawPixel(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;
    if (color)
        s_vram[y / 8 * SSD1306_WIDTH + x] |= (1 << (y % 8));
    else
        s_vram[y / 8 * SSD1306_WIDTH + x] &= ~(1 << (y % 8));
}

/* col: 0~21 (6像素列), page: 0~7 (8像素行) */
void SSD1306_ShowChar(uint8_t col, uint8_t page, char ch)
{
    if (ch < ' ' || ch > '~') ch = '?';
    const uint8_t *glyph = FONT6x8[ch - ' '];
    uint16_t base = page * SSD1306_WIDTH + col * 6;
    for (uint8_t i = 0; i < 6 && (base + i) < sizeof(s_vram); i++)
        s_vram[base + i] = glyph[i];
}

void SSD1306_ShowString(uint8_t col, uint8_t page, const char *str)
{
    while (*str) {
        SSD1306_ShowChar(col, page, *str++);
        if (++col > 21) { col = 0; if (++page > 7) return; }
    }
}

void SSD1306_ShowFloat(uint8_t col, uint8_t page, float val, uint8_t decimals)
{
    char buf[16];
    snprintf(buf, sizeof(buf), "%.*f", decimals, (double)val);
    SSD1306_ShowString(col, page, buf);
}

/* 8x16 大字号: 将 6x8 字库行列放大 2 倍并加粗一行 */
void SSD1306_ShowBigNumber(uint8_t col, uint8_t page, float val, uint8_t decimals)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%.*f", decimals, (double)val);
    uint8_t c = col;
    for (uint8_t k = 0; buf[k] && k < 10; k++) {
        if (buf[k] < ' ' || buf[k] > '~') buf[k] = '?';
        const uint8_t *g = FONT6x8[buf[k] - ' '];
        for (uint8_t i = 0; i < 6; i++) {
            uint8_t bits = g[i];
            for (uint8_t b = 0; b < 8; b++) {
                uint8_t on = (bits >> b) & 1;
                /* 每个逻辑像素扩展为 2x2 */
                for (uint8_t dx = 0; dx < 2; dx++) {
                    SSD1306_DrawPixel(c * 6 * 2 + i * 2 + dx,
                                      page * 8 + b * 2, on);
                    SSD1306_DrawPixel(c * 6 * 2 + i * 2 + dx,
                                      page * 8 + b * 2 + 1, on);
                }
            }
        }
        c++;
    }
}
